// Generate the parity schema from the canonical, empty SQLite migration result.
// This script never opens a deployment database or reads user data.
import {DatabaseSync} from 'node:sqlite'
import {readFileSync,writeFileSync} from 'node:fs'
const args=process.argv.slice(2)
if(args.some(arg=>arg!=='--check')||args.length>1)throw Error('Usage: generate-domain-schema.mjs [--check]')
import {createHash} from 'node:crypto'
import {MIGRATIONS} from '../../../apps/core/src/storage/schema.ts'
const sqlite=new DatabaseSync(':memory:')
for(const migration of MIGRATIONS)sqlite.exec(migration.sql)
const camel=name=>name.replace(/_([a-z])/g,(_,letter)=>letter.toUpperCase())
const quote=JSON.stringify
const short=name=>name.length<=63?name:name.slice(0,54)+'_'+createHash('sha256').update(name).digest('hex').slice(0,8)
const ordinalTables=new Set(['terminal_commands','managed_operations','managed_compactions'])
const rows=sqlite.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name NOT IN ('migrations','sessions','messages','parts') ORDER BY name").all()
const lines=["// Generated by scripts/generate-domain-schema.mjs; edit the canonical SQLite schema or reviewed overrides, then regenerate.","// Serialized JSON and encrypted strings intentionally retain their original representation for migration parity.","import {sql} from 'drizzle-orm'","import {bigint,check,doublePrecision,index,pgTable,primaryKey,text,uniqueIndex,type AnyPgColumn} from 'drizzle-orm/pg-core'","import {sessions,messages,parts} from './conversation-schema.js'"]
function checks(sql){const found=[];const regex=/\bCHECK\s*\(/gi;let match;while((match=regex.exec(sql))){const start=regex.lastIndex;let level=1,quoted=false,i=start;for(;i<sql.length&&level;i++){const char=sql[i];if(char==="'"){if(quoted&&sql[i+1]==="'"){i++;continue}quoted=!quoted}else if(!quoted){if(char==='(')level++;if(char===')')level--}}if(level)throw Error('Unbalanced CHECK');found.push(sql.slice(start,i-1));regex.lastIndex=i}return found}
for(const table of rows){
 const columns=sqlite.prepare(`PRAGMA table_info(${quote(table.name)})`).all(),keys=columns.filter(column=>column.pk).sort((a,b)=>a.pk-b.pk),foreign=sqlite.prepare(`PRAGMA foreign_key_list(${quote(table.name)})`).all()
 const definitions=[]
 for(const column of columns){
  let value=column.type==='TEXT'?`text(${quote(column.name)})`:column.type==='INTEGER'?`bigint(${quote(column.name)},{mode:'number'})`:column.type==='REAL'?`doublePrecision(${quote(column.name)})`:undefined
  if(!value)throw Error('Unsupported column type: '+table.name+'.'+column.name)
  if(keys.length===1&&column.pk){
   if(column.type==='INTEGER'&&/\bAUTOINCREMENT\b/i.test(table.sql))value+='.generatedByDefaultAsIdentity()'
   value+='.primaryKey()'
  }else if(column.notnull||column.pk)value+='.notNull()'
  if(column.dflt_value!==null){const d=column.dflt_value;if(/^'.*'$/s.test(d))value+=`.default(${quote(d.slice(1,-1).replaceAll("''","'"))})`;else if(/^-?\d+$/.test(d))value+=`.default(${Number(d)})`;else if(d.toUpperCase()!=='NULL')throw Error('Unsupported default: '+table.name+'.'+column.name)}
  const refs=foreign.filter(f=>f.from===column.name)
  for(const ref of refs){if(ref.seq!==0||foreign.filter(f=>f.id===ref.id).length!==1)throw Error('Composite foreign key requires review');value+=`.references(():AnyPgColumn=>${camel(ref.table)}.${camel(ref.to)}${ref.on_delete==='NO ACTION'?'':`,{onDelete:${quote(ref.on_delete.toLowerCase())}}`})`}
  definitions.push(` ${camel(column.name)}:${value},`)
 }
 if(ordinalTables.has(table.name))definitions.push(" ordinal:bigint('ordinal',{mode:'number'}).generatedByDefaultAsIdentity().notNull(),")
 const extras=[]
 if(keys.length>1)extras.push(`primaryKey({columns:[${keys.map(c=>'table.'+camel(c.name)).join(',')}]})`)
 for(const item of sqlite.prepare(`PRAGMA index_list(${quote(table.name)})`).all()){
  if(item.origin==='pk')continue
  const cols=sqlite.prepare(`PRAGMA index_xinfo(${quote(item.name)})`).all().filter(c=>c.key)
  if(cols.some(c=>!c.name))throw Error('Expression index requires review: '+item.name)
  const name=short(item.name.startsWith('sqlite_autoindex')?table.name+'_'+cols.map(c=>c.name).join('_')+'_unique':item.name)
  let index=`${item.unique?'uniqueIndex':'index'}(${quote(name)}).on(${cols.map(c=>'table.'+camel(c.name)+(c.desc?'.desc()':'')).join(',')})`
  if(item.partial){const definition=sqlite.prepare('SELECT sql FROM sqlite_master WHERE name=?').get(item.name)?.sql,where=definition?.match(/\bWHERE\s+([\s\S]*)$/i)?.[1];if(!where)throw Error('Missing partial-index predicate');index+=`.where(sql.raw(${quote(where)}))`}
  extras.push(index)
 }
 checks(table.sql).forEach((expression,i)=>extras.push(`check(${quote(short(table.name+'_check_'+i))},sql.raw(${quote(expression)}))`))
 lines.push(`export const ${camel(table.name)}=pgTable(${quote(table.name)},{\n${definitions.join('\n')}\n}${extras.length?`,table=>[\n ${extras.join(',\n ')}\n]`:''})`)
}
lines.push(`export const domainSchema={${rows.map(row=>camel(row.name)).join(',')}}`)
const output=new URL('../src/postgres/domain-schema.ts',import.meta.url),source=lines.join('\n')+'\n'
sqlite.close()
if(args.includes('--check')){
 if(readFileSync(output,'utf8')!==source)throw Error('PostgreSQL domain schema is stale; review and run generate-domain-schema.mjs')
 console.log(`PostgreSQL domain schema is up to date (${rows.length} domain tables).`)
}else{
 writeFileSync(output,source)
 console.log(`Generated ${rows.length} domain tables from an empty SQLite schema; no deployment data accessed.`)
}
